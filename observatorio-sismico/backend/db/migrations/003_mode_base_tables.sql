-- @per-schema
-- Mismo DDL que la migración 001 (inmutable), aplicado a cada esquema de modo. Idempotente:
-- en `demo` las tablas ya existen (movidas desde public) y no se tocan.
CREATE TABLE IF NOT EXISTS event_message (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT NOT NULL CHECK (length(trim(event_id)) > 0),
    updated_ms BIGINT NOT NULL CHECK (updated_ms >= 0),
    source TEXT NOT NULL CHECK (length(trim(source)) > 0),
    mode TEXT NOT NULL CHECK (mode IN ('demo', 'live', 'replay')),
    ingested_at TIMESTAMPTZ NOT NULL,
    synthetic_flag BOOLEAN NOT NULL,
    payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT uq_event_message_version UNIQUE (event_id, updated_ms),
    CONSTRAINT uq_event_message_reference
        UNIQUE (message_id, event_id, updated_ms)
);

CREATE TABLE IF NOT EXISTS event_current (
    event_id TEXT PRIMARY KEY CHECK (length(trim(event_id)) > 0),
    message_id BIGINT NOT NULL,
    current_version_ms BIGINT NOT NULL CHECK (current_version_ms >= 0),
    last_seen_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_event_current_message
        FOREIGN KEY (message_id, event_id, current_version_ms)
        REFERENCES event_message (message_id, event_id, updated_ms)
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS quarantine_record (
    quarantine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT,
    source TEXT,
    reason TEXT NOT NULL CHECK (length(trim(reason)) > 0),
    original_payload TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    kafka_topic TEXT,
    kafka_partition INTEGER,
    kafka_offset BIGINT,
    CONSTRAINT ck_quarantine_kafka_reference CHECK (
        (kafka_topic IS NULL AND kafka_partition IS NULL AND kafka_offset IS NULL)
        OR
        (
            kafka_topic IS NOT NULL
            AND kafka_partition IS NOT NULL
            AND kafka_offset IS NOT NULL
            AND kafka_partition >= 0
            AND kafka_offset >= 0
        )
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_quarantine_kafka_offset
    ON quarantine_record (kafka_topic, kafka_partition, kafka_offset)
    WHERE kafka_topic IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_event_message_ingested_at
    ON event_message (ingested_at);

CREATE INDEX IF NOT EXISTS ix_quarantine_created_at
    ON quarantine_record (created_at);
