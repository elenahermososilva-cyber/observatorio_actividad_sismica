-- D1: estado persistente del productor, fuera de los esquemas de datos por modo.
-- published_version: qué versiones (event_id, updated) se han publicado ya en Kafka, por modo.
--   Se marca SOLO tras el ack de Kafka; si el proceso cae entre ambas cosas puede reenviarse un mensaje
--   y el consumidor lo tolera (idempotencia).
CREATE TABLE IF NOT EXISTS ingest.published_version (
    mode TEXT NOT NULL CHECK (mode IN ('demo', 'live', 'replay')),
    event_id TEXT NOT NULL CHECK (length(trim(event_id)) > 0),
    updated_ms BIGINT NOT NULL CHECK (updated_ms >= 0),
    published_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (mode, event_id, updated_ms)
);

-- extraction_log: una fila por consulta al feed/API de USGS (procedencia, auditoría y `last_ingestion`).
--   ok = la respuesta fue válida; solo las consultas ok mueven `last_ingestion`.
--   La fila de un error conserva el motivo sin borrar el estado válido anterior.
CREATE TABLE IF NOT EXISTS ingest.extraction_log (
    extraction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode TEXT NOT NULL CHECK (mode IN ('demo', 'live', 'replay')),
    source_url TEXT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    latency_ms INTEGER CHECK (latency_ms >= 0),
    http_status INTEGER,
    ok BOOLEAN NOT NULL,
    record_count INTEGER CHECK (record_count >= 0),
    response_bytes BIGINT CHECK (response_bytes >= 0),
    response_sha256 TEXT,
    raw_path TEXT,                  -- archivo original conservado (NULL si era idéntico a uno ya guardado)
    error TEXT,
    CONSTRAINT ck_extraction_ok_has_no_error CHECK (NOT ok OR error IS NULL),
    CONSTRAINT ck_extraction_failure_has_error CHECK (ok OR error IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS ix_extraction_log_mode_started
    ON ingest.extraction_log (mode, started_at DESC);
CREATE INDEX IF NOT EXISTS ix_extraction_log_ok_started
    ON ingest.extraction_log (mode, started_at DESC) WHERE ok;
